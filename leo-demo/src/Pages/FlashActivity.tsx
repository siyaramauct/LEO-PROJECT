import { useParams } from "react-router-dom";
import Flashcard from "../Components/Flashcard";
import Navbar from "../Components/Navbar";
import { useState } from "react";
import { CheckIcon, XMarkIcon , SparklesIcon, LightBulbIcon} from "@heroicons/react/24/solid";

export default function FlashActivity() {
    const params = useParams();   
    
    const flashcards = [
        { word: "Revenue", definition: "The total income generated by a business." },
        { word: "Profit", definition: "The financial gain after subtracting expenses from revenue." },
    ];

    const [flashcardIndex, setFlashcardIndex] = useState(0);
    const [score, setScore] = useState(0);

    function nextFlashCard(){
        if(flashcardIndex == flashcards.length - 1){
            alert(`Your score: ${score} / ${flashcards.length}`);
            setFlashcardIndex(0);
            setScore(0);
            return; 
        }
        setFlashcardIndex(previousIndex => previousIndex + 1);
    }

    const currentFlashCard = flashcards[flashcardIndex];

    return (
        <div className="w-full flex flex-col items-center">
            <Navbar />
            <div className="w-full max-w-sm mx-auto mt-6 bg-white  overflow-hidden ">
                <div className="w-full h-35 overflow-hidden">
                    <img
                        src="/corporateStyleLessonIlustration.avif"
                        alt="Lesson illustration"
                        className="w-full h-full object-cover"
                    />
                </div>
                <div className="px-4 pt-3 pb-4 flex flex-col gap-1">
                    <span className="text-[10px] font-semibold text-violet-500 text-center uppercase tracking-widest">Flashcards</span>
                    <h2 className="text-[13px] font-bold text-gray-800 leading-snug text-center">Lesson {params.lessonId}</h2>
                    <div className="mt-2">
                        <div className="flex justify-between items-center mb-1.5">
                            <span className="text-[10px] text-gray-400">{flashcards.length} cards</span>
                            <span className="text-[11px] font-bold text-violet-600">{flashcardIndex + 1} / {flashcards.length}</span>
                        </div>
                        <div className="w-full bg-gray-200 rounded-full h-2.5 overflow-hidden">
                            <div
                                className="h-full rounded-full bg-violet-600 transition-all duration-500"
                                style={{ width: `${((flashcardIndex + 1) / flashcards.length) * 100}%` }}
                            />
                        </div>
                    </div>
                </div>
            </div>
            <section className="w-full px-4 flex flex-col items-center justify-center min-h-[calc(100vh-25rem)] gap-8 mt-5">
                <Flashcard word={currentFlashCard.word} definition={currentFlashCard.definition} />
                <div className="flex items-center gap-12 mt-4 ">
                    <button
                        className="flex items-center justify-center w-16 h-16 rounded-full bg-violet-700 text-red-500 active:scale-95 transition-transform shadow-md"
                        aria-label="Wrong"
                        onClick={nextFlashCard}
                    >
                        <XMarkIcon className="w-8 h-8 text-white" />
                    </button>
                    <button
                        className="flex items-center justify-center w-16 h-16 rounded-full bg-violet-700 text-green-500 active:scale-95 transition-transform shadow-md"
                        aria-label="Correct"
                    >
                        <CheckIcon className="w-8 h-8 text-white" />
                    </button>
                </div>
            </section>

        </div>
    );
}